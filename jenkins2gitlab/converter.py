"""Translate a parsed declarative Jenkinsfile into a GitLab CI configuration."""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from . import yamlout
from .parser import Block, Statement, parse

# Jenkins built-in environment variables -> GitLab predefined variables
ENV_MAP = {
    "BRANCH_NAME": "CI_COMMIT_REF_NAME",
    "BUILD_NUMBER": "CI_PIPELINE_IID",
    "BUILD_ID": "CI_PIPELINE_ID",
    "BUILD_URL": "CI_PIPELINE_URL",
    "GIT_COMMIT": "CI_COMMIT_SHA",
    "GIT_BRANCH": "CI_COMMIT_REF_NAME",
    "TAG_NAME": "CI_COMMIT_TAG",
    "WORKSPACE": "CI_PROJECT_DIR",
    "JOB_NAME": "CI_PROJECT_NAME",
    "CHANGE_ID": "CI_MERGE_REQUEST_IID",
    "CHANGE_TARGET": "CI_MERGE_REQUEST_TARGET_BRANCH_NAME",
}

# Commands that only prepare the workspace. Jenkins stages share one workspace,
# GitLab jobs do not - so a stage made only of these must run before every job.
INSTALL_CMD = re.compile(
    r"^\s*(pip3?|python3? -m pip) install\b|^\s*npm (ci|install)\b|^\s*yarn( install)?\s*$|"
    r"^\s*(poetry|bundle|pipenv) install\b|^\s*mvn\b.*dependency:(go-offline|resolve)"
)

UNIT_WORDS = {"SECONDS": "seconds", "MINUTES": "minutes", "HOURS": "hours", "DAYS": "days"}


@dataclass
class Finding:
    level: str  # "info" or "manual"
    where: str
    message: str

    def __str__(self) -> str:
        tag = "MANUAL" if self.level == "manual" else "info"
        return f"[{tag}] {self.where}: {self.message}"


@dataclass
class Result:
    config: dict
    findings: list[Finding] = field(default_factory=list)

    @property
    def manual_items(self) -> list[Finding]:
        return [f for f in self.findings if f.level == "manual"]

    def to_yaml(self) -> str:
        header = [
            "Generated by jenkins2gitlab from a declarative Jenkinsfile.",
            f"Automatic conversions: {len(self.findings) - len(self.manual_items)}"
            f" | Items that need manual review: {len(self.manual_items)}",
        ]
        if self.manual_items:
            header.append("")
            header.append("Manual review:")
            header.extend(f"  - {f.where}: {f.message}" for f in self.manual_items)
        return yamlout.dump(self.config, header="\n".join(header))


# --------------------------------------------------------------------------
# Groovy argument helpers
# --------------------------------------------------------------------------

def _split_top(s: str, sep: str = ",") -> list[str]:
    parts, depth, cur, i = [], 0, [], 0
    while i < len(s):
        c = s[i]
        if c in "'\"":
            q3 = s[i:i + 3]
            if q3 in ("'''", '"""'):
                end = s.find(q3, i + 3)
                end = len(s) if end == -1 else end + 3
            else:
                end = i + 1
                while end < len(s) and s[end] != c:
                    end += 2 if s[end] == "\\" else 1
                end += 1
            cur.append(s[i:end])
            i = end
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == sep and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    if "".join(cur).strip():
        parts.append("".join(cur).strip())
    return parts


def unquote(v: str) -> str:
    v = v.strip()
    for q in ("'''", '"""'):
        if v.startswith(q) and v.endswith(q) and len(v) >= 6:
            text = _dedent(v[3:-3])
            return text.replace("\\$", "$") if q == '"""' else text
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
        inner = v[1:-1]
        if v[0] == '"':
            inner = inner.replace("\\$", "$")
        return inner.replace("\\'", "'").replace('\\"', '"').replace("\\\\", "\\")
    return v


def _dedent(text: str) -> str:
    lines = text.strip("\n").split("\n")
    widths = [len(ln) - len(ln.lstrip()) for ln in lines if ln.strip()]
    cut = min(widths) if widths else 0
    return "\n".join(ln[cut:] for ln in lines)


def parse_args(raw: str) -> tuple[list[str], dict[str, str]]:
    """Split Groovy call arguments into positional and named values (still raw)."""
    raw = raw.strip()
    if raw.startswith("(") and raw.endswith(")"):
        raw = raw[1:-1]
    pos, named = [], {}
    for part in _split_top(raw):
        m = re.match(r"^([A-Za-z_]\w*)\s*:\s*(.+)$", part, re.S)
        if m and not part.startswith(("'", '"')):
            named[m.group(1)] = m.group(2).strip()
        else:
            pos.append(part)
    return pos, named


def split_call(text: str) -> tuple[str, str]:
    """``sh 'make'`` -> ("sh", "'make'"); ``junit(testResults: 'x')`` -> ("junit", "testResults: 'x'")."""
    m = re.match(r"^([A-Za-z_][\w.]*)\s*(.*)$", text.strip(), re.S)
    if not m:
        return "", text
    name, rest = m.group(1), m.group(2).strip()
    if rest.startswith("(") and rest.endswith(")"):
        rest = rest[1:-1]
    return name, rest


def map_env_refs(text: str) -> str:
    """Rewrite Jenkins-specific variable references for GitLab."""
    text = re.sub(r"\$\{\s*(?:env|params)\.(\w+)\s*\}", r"${\1}", text)
    text = re.sub(r"\$(?:env|params)\.(\w+)", r"$\1", text)
    for jk, gl in ENV_MAP.items():
        text = re.sub(r"\$\{" + jk + r"\}", "${" + gl + "}", text)
        text = re.sub(r"\$" + jk + r"\b", "$" + gl, text)
    return text


def _merge_rules(outer: list, inner: list) -> list:
    """Combine rules of a parent stage and a nested stage (both must match)."""
    if not outer:
        return inner
    if not inner:
        return outer
    merged = dict(outer[0])
    if "if" in inner[0]:
        merged["if"] = f"({merged['if']}) && ({inner[0]['if']})" if "if" in merged else inner[0]["if"]
    if "changes" in inner[0]:
        merged["changes"] = merged.get("changes", []) + inner[0]["changes"]
    return [merged]


def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s or "job"


def _duration(named: dict[str, str], pos: list[str]) -> str | None:
    t = named.get("time") or (pos[0] if pos else None)
    if t is None:
        return None
    unit = unquote(named.get("unit", "'MINUTES'")).upper()
    return f"{unquote(t)} {UNIT_WORDS.get(unit, 'minutes')}"


# --------------------------------------------------------------------------
# Converter
# --------------------------------------------------------------------------

class Converter:
    def __init__(self) -> None:
        self.findings: list[Finding] = []
        self.stages: list[str] = []
        self.jobs: dict[str, dict] = {}
        self.install_lines: list[str] = []

    # reporting
    def info(self, where: str, msg: str) -> None:
        self.findings.append(Finding("info", where, msg))

    def manual(self, where: str, msg: str) -> None:
        self.findings.append(Finding("manual", where, msg))

    # ------------------------------------------------------------------
    def convert(self, src: str) -> Result:
        pipe = parse(src)
        config: dict = {}
        default: dict = {}
        variables: dict = {}

        agent = pipe.block("agent")
        top_agent_stmt = next((s for s in pipe.statements() if s.text.startswith("agent")), None)
        if agent:
            self._agent(agent, default, "pipeline")
        elif top_agent_stmt:
            val = top_agent_stmt.text.split(None, 1)[1] if " " in top_agent_stmt.text else ""
            if val == "any":
                self.info("pipeline", "'agent any' -> any available runner; set a default image if jobs need specific tools")
            elif val == "none":
                self.info("pipeline", "'agent none' -> each job chooses its own image")

        env = pipe.block("environment")
        if env:
            variables.update(self._environment(env, "pipeline"))

        params = pipe.block("parameters")
        if params:
            variables.update(self._parameters(params))

        opts = pipe.block("options")
        if opts:
            self._options(opts, default)

        tools = pipe.block("tools")
        if tools:
            self.manual("pipeline.tools", "Jenkins 'tools' ("
                        + ", ".join(s.text for s in tools.statements())
                        + ") - pick a Docker image that already contains these, e.g. maven:3-eclipse-temurin-17")

        trig = pipe.block("triggers")
        if trig:
            self._triggers(trig)

        stages = pipe.block("stages")
        if stages is None:
            raise ValueError("pipeline has no 'stages' block")
        for st in stages.blocks("stage"):
            self._stage(st, inherited_rules=None, stage_name=None)

        post = pipe.block("post")
        if post:
            self._pipeline_post(post)

        if self.install_lines:
            default["before_script"] = self.install_lines
        if default:
            config["default"] = default
        config["stages"] = self.stages
        if variables:
            config["variables"] = variables
        config.update(self.jobs)
        return Result(config=config, findings=self.findings)

    # ------------------------------------------------------------------
    def _agent(self, agent: Block, target: dict, where: str) -> None:
        docker = agent.block("docker")
        if docker:
            for s in docker.statements():
                name, rest = split_call(s.text)
                if name == "image":
                    target["image"] = unquote(rest)
                elif name == "args":
                    self.manual(where, f"docker agent args {rest} - move to runner config or job 'services'")
                elif name == "label":
                    target.setdefault("tags", []).append(unquote(rest))
            self.info(where, f"docker agent -> image: {target.get('image')}")
            return
        for s in agent.statements():
            name, rest = split_call(s.text)
            if name == "label":
                target.setdefault("tags", []).append(unquote(rest))
                self.info(where, f"agent label {rest} -> runner tag")
            elif s.text.strip() in ("any", "none"):
                pass
            else:
                self.manual(where, f"agent option '{s.text}' has no direct equivalent")
        if agent.block("dockerfile"):
            self.manual(where, "agent dockerfile - build the image in an earlier job and use it via $CI_REGISTRY_IMAGE")
        if agent.block("kubernetes"):
            self.manual(where, "kubernetes agent - use a GitLab runner with the Kubernetes executor and set 'image'")
        if agent.block("node"):
            for s in agent.block("node").statements():
                name, rest = split_call(s.text)
                if name == "label":
                    target.setdefault("tags", []).append(unquote(rest))

    def _environment(self, env: Block, where: str) -> dict:
        out = {}
        for s in env.statements():
            if "=" not in s.text:
                continue
            key, val = (x.strip() for x in s.text.split("=", 1))
            if val.startswith("credentials("):
                cred = unquote(val[len("credentials("):-1])
                self.manual(where, f"credential '{cred}' used as {key} - create a masked/protected CI/CD variable "
                                   f"named {key} in Settings > CI/CD > Variables (or read it from Vault)")
                continue
            out[key] = map_env_refs(unquote(val))
        if out:
            self.info(where, f"environment -> variables ({', '.join(out)})")
        return out

    def _parameters(self, params: Block) -> dict:
        out = {}
        for s in params.statements():
            kind, rest = split_call(s.text)
            _, named = parse_args(rest)
            name = unquote(named.get("name", "''"))
            if not name:
                continue
            desc = unquote(named.get("description", "''"))
            if kind == "choice":
                choices = named.get("choices", "[]").strip("[]")
                opts = [unquote(c) for c in _split_top(choices)]
                entry = {"value": opts[0] if opts else "", "options": opts}
            elif kind == "booleanParam":
                entry = {"value": unquote(named.get("defaultValue", "false"))}
            else:
                entry = {"value": unquote(named.get("defaultValue", "''"))}
            if desc:
                entry["description"] = desc
            out[name] = entry
        if out:
            self.info("pipeline.parameters", f"build parameters -> prefilled pipeline variables ({', '.join(out)})")
        return out

    def _options(self, opts: Block, default: dict) -> None:
        for s in opts.statements():
            name, rest = split_call(s.text)
            pos, named = parse_args(rest)
            if name == "timeout":
                default["timeout"] = _duration(named, pos)
                self.info("pipeline.options", f"timeout -> default timeout {default['timeout']}")
            elif name == "retry":
                n = int(unquote(pos[0])) if pos else 1
                default["retry"] = max(0, min(2, n - 1))
                self.info("pipeline.options", f"retry({n}) -> retry: {default['retry']} (GitLab allows at most 2)")
            elif name == "disableConcurrentBuilds":
                self.manual("pipeline.options", "disableConcurrentBuilds - add 'resource_group' to deploy jobs, "
                                                "or enable 'auto-cancel redundant pipelines'")
            elif name == "buildDiscarder":
                self.info("pipeline.options", "buildDiscarder -> use artifacts:expire_in and project retention settings")
            elif name == "skipDefaultCheckout":
                default.setdefault("variables", {})["GIT_STRATEGY"] = "none"
                self.info("pipeline.options", "skipDefaultCheckout -> GIT_STRATEGY: none")
            elif name == "timestamps":
                self.info("pipeline.options", "timestamps - GitLab job logs already have timestamps")
            else:
                self.manual("pipeline.options", f"option '{s.text}' not translated")

    def _triggers(self, trig: Block) -> None:
        for s in trig.statements():
            name, rest = split_call(s.text)
            if name == "cron":
                spec = unquote(parse_args(rest)[0][0]) if rest else ""
                spec = re.sub(r"\bH\b", "0", spec)
                self.manual("pipeline.triggers", f"cron -> create a pipeline schedule '{spec}' (Build > Pipeline schedules)")
            elif name == "pollSCM":
                self.info("pipeline.triggers", "pollSCM not needed - GitLab runs pipelines on every push")
            else:
                self.manual("pipeline.triggers", f"trigger '{s.text}' - use pipeline triggers or multi-project pipelines")

    # ------------------------------------------------------------------
    def _add_stage(self, name: str) -> str:
        s = slug(name)
        if s not in self.stages:
            self.stages.append(s)
        return s

    def _stage(self, st: Block, inherited_rules: list | None, stage_name: str | None,
               prefix: str = "", inherit: dict | None = None) -> None:
        title = unquote(st.args) or "stage"
        where = f"stage '{title}'"
        rules = list(inherited_rules or [])
        when = st.block("when")
        extra_job: dict = {}
        if when:
            rules = _merge_rules(rules, self._when(when, where))

        # Nested sequential stages and parallel groups
        par = st.block("parallel")
        if par:
            gl_stage = self._add_stage(prefix + title)
            for child in par.blocks("stage"):
                self._stage(child, rules, gl_stage, prefix, inherit)
            self.info(where, "parallel -> jobs in the same stage run in parallel")
            return
        nested = st.block("stages")
        if nested:
            for child in nested.blocks("stage"):
                self._stage(child, rules, None, prefix=f"{title} ", inherit=inherit)
            return

        matrix = st.block("matrix")
        if matrix and matrix.block("stages"):
            # matrix { axes {...} stages { stage {...} } } -> each inner stage becomes a matrix job
            gl_stage = stage_name or self._add_stage(prefix + title)
            base: dict = dict(inherit or {})
            self._matrix(matrix, base, where)
            m_agent = matrix.block("agent")
            if m_agent:
                self._agent(m_agent, base, where)
            for child in matrix.block("stages").blocks("stage"):
                self._stage(child, rules, gl_stage, prefix, base)
            return

        gl_stage = stage_name or self._add_stage(prefix + title)
        job: dict = {"stage": gl_stage}
        for k, v in (inherit or {}).items():
            job[k] = v.copy() if isinstance(v, (dict, list)) else v

        agent = st.block("agent")
        if agent:
            self._agent(agent, job, where)

        env = st.block("environment")
        if env:
            v = self._environment(env, where)
            if v:
                job["variables"] = v

        opts = st.block("options")
        if opts:
            for s in opts.statements():
                name, rest = split_call(s.text)
                pos, named = parse_args(rest)
                if name == "timeout":
                    job["timeout"] = _duration(named, pos)
                elif name == "retry":
                    n = int(unquote(pos[0])) if pos else 1
                    job["retry"] = max(0, min(2, n - 1))
                else:
                    self.manual(where, f"stage option '{s.text}' not translated")

        if st.block("input") or any(s.text.startswith("input") for s in st.statements()):
            extra_job["when"] = "manual"
            self.info(where, "input -> when: manual (approve by clicking 'play' in the pipeline)")

        matrix = st.block("matrix")
        if matrix:
            self._matrix(matrix, job, where)
            steps_owner = matrix
        else:
            steps_owner = st

        steps = steps_owner.block("steps")
        script: list[str] = []
        if steps:
            script = self._steps(steps.children, job, where)
        else:
            self.manual(where, "stage has no 'steps' block")
        if not script and not job.get("artifacts"):
            self.info(where, "stage has nothing left to run in GitLab - job dropped")
            if not stage_name and gl_stage in self.stages and not any(
                    j.get("stage") == gl_stage for j in self.jobs.values()):
                self.stages.remove(gl_stage)
            return
        if not script:
            script = ['echo "Artifacts collected"']
        job["script"] = script
        if any(re.search(r"\bdocker (build|push|login)\b", ln) for ln in script):
            self.manual(where, "job runs docker commands - use a runner with Docker access, or "
                               "image: docker:27 with services: [docker:27-dind]")

        post = steps_owner.block("post") or st.block("post")
        if post:
            self._stage_post(post, job, where)

        if rules:
            job["rules"] = rules
        job.update(extra_job)
        if job.get("when") == "manual" and "rules" in job:
            for rule in job["rules"]:
                rule["when"] = "manual"
            del job["when"]

        if (not stage_name and set(job) <= {"stage", "script"}
                and all(INSTALL_CMD.search(ln) for ln in script)):
            self.install_lines.extend(script)
            self.stages.remove(gl_stage)
            self.info(where, "dependency-install stage moved to default:before_script - Jenkins stages share a "
                             "workspace but every GitLab job starts clean")
            return

        name = slug(prefix + title)
        while name in self.jobs:
            name += "-2"
        self.jobs[name] = self._order(job)

    @staticmethod
    def _order(job: dict) -> dict:
        order = ["stage", "image", "tags", "variables", "parallel", "timeout", "retry", "needs",
                 "script", "after_script", "artifacts", "rules", "when", "allow_failure", "resource_group"]
        comments = {k: v for k, v in job.items() if k.startswith("#")}
        ordered = dict(comments)
        ordered.update({k: job[k] for k in order if k in job})
        ordered.update({k: v for k, v in job.items() if k not in ordered})
        return ordered

    def _matrix(self, matrix: Block, job: dict, where: str) -> None:
        axes = matrix.block("axes")
        combo: dict = {}
        if axes:
            for axis in axes.blocks("axis"):
                name, values = None, []
                for s in axis.statements():
                    k, rest = split_call(s.text)
                    if k == "name":
                        name = unquote(rest)
                    elif k == "values":
                        values = [unquote(v) for v in _split_top(rest)]
                if name:
                    combo[name] = values
        if combo:
            job["parallel"] = {"matrix": [combo]}
            self.info(where, f"matrix -> parallel:matrix over {', '.join(combo)}")
        if matrix.block("excludes"):
            self.manual(where, "matrix excludes - GitLab matrix has no excludes; split into several matrix entries")

    # ------------------------------------------------------------------
    def _when(self, when: Block, where: str) -> list:
        conds, changes = [], []

        def cond_of(stmt_text: str) -> str | None:
            name, rest = split_call(stmt_text)
            pos, named = parse_args(rest)
            if name == "branch":
                pat = unquote(named.get("pattern", pos[0] if pos else "''"))
                if "*" in pat or "?" in pat:
                    rx = re.escape(pat).replace(r"\*\*", ".*").replace(r"\*", ".*").replace(r"\?", ".").replace("/", r"\/")
                    return f"$CI_COMMIT_BRANCH =~ /^{rx}$/"
                return f'$CI_COMMIT_BRANCH == "{pat}"'
            if name == "tag":
                if not pos and not named:
                    return "$CI_COMMIT_TAG"
                pat = unquote(named.get("pattern", pos[0] if pos else "''"))
                rx = re.escape(pat).replace(r"\*", ".*").replace("/", r"\/")
                return f"$CI_COMMIT_TAG =~ /^{rx}$/"
            if name == "buildingTag":
                return "$CI_COMMIT_TAG"
            if name == "changeRequest":
                return '$CI_PIPELINE_SOURCE == "merge_request_event"'
            if name == "environment":
                var = unquote(named.get("name", "''"))
                val = unquote(named.get("value", "''"))
                return f'${var} == "{val}"'
            if name == "changeset":
                changes.append(unquote(pos[0] if pos else named.get("pattern", "''")))
                return None
            if name == "beforeAgent" or name == "beforeInput":
                return None
            self.manual(where, f"when condition '{stmt_text}' needs a manual 'rules:if'")
            return None

        for s in when.statements():
            c = cond_of(s.text)
            if c:
                conds.append(c)
        for b in when.blocks():
            inner = [cond_of(s.text) for s in b.statements()]
            inner = [c for c in inner if c]
            if b.name == "not" and inner:
                c = inner[0]
                c = c.replace(" == ", " != ").replace(" =~ ", " !~ ")
                if c in ("$CI_COMMIT_TAG",):
                    c = "$CI_COMMIT_TAG == null"
                conds.append(c)
            elif b.name == "anyOf" and inner:
                conds.append("(" + " || ".join(inner) + ")")
            elif b.name == "allOf" and inner:
                conds.extend(inner)
            elif b.name == "expression":
                self.manual(where, "when { expression { ... } } is Groovy logic - rewrite as a 'rules:if' expression: "
                            + " ".join(s.text for s in b.statements()))
        rule: dict = {}
        if conds:
            rule["if"] = " && ".join(conds)
        if changes:
            rule["changes"] = changes
        if rule:
            self.info(where, "when -> rules")
            return [rule]
        return []

    # ------------------------------------------------------------------
    def _steps(self, children, job: dict, where: str) -> list[str]:
        lines: list[str] = []
        for child in children:
            if isinstance(child, Block):
                lines.extend(self._step_block(child, job, where))
            else:
                lines.extend(self._step(child, job, where))
        return lines

    def _step_block(self, b: Block, job: dict, where: str) -> list[str]:
        pos, named = parse_args(b.args)
        if b.name == "dir":
            path = unquote(pos[0]) if pos else "."
            return [f"cd {path}"] + self._steps(b.children, job, where) + ['cd "$CI_PROJECT_DIR"']
        if b.name == "withEnv":
            pairs = [unquote(p) for p in _split_top(b.args.strip().strip("[]"))]
            return [f"export {map_env_refs(p)}" for p in pairs] + self._steps(b.children, job, where)
        if b.name == "withCredentials":
            ids = re.findall(r"credentialsId\s*:\s*['\"]([^'\"]+)['\"]", b.args)
            vars_ = re.findall(r"(?:variable|usernameVariable|passwordVariable|keyFileVariable)\s*:\s*['\"]([^'\"]+)['\"]",
                               b.args)
            kind = "File-type" if re.search(r"\bfile\s*\(", b.args) else "masked"
            self.manual(where, f"withCredentials({', '.join(ids)}) - create {kind} CI/CD variable(s) "
                               f"{', '.join(vars_)} (or fetch them from Vault with 'secrets:')")
            return self._steps(b.children, job, where)
        if b.name == "timeout":
            job["timeout"] = _duration(named, pos)
            return self._steps(b.children, job, where)
        if b.name == "retry":
            n = int(unquote(pos[0])) if pos else 1
            job["retry"] = max(0, min(2, n - 1))
            self.info(where, f"retry({n}) -> retry: {job['retry']}")
            return self._steps(b.children, job, where)
        if b.name in ("sshagent", "withDockerRegistry", "withAWS", "withKubeConfig"):
            self.manual(where, f"{b.name}(...) - provide these credentials as CI/CD variables and log in inside 'script'")
            return self._steps(b.children, job, where)
        if b.name == "script":
            raw = [s.text for s in b.children if isinstance(s, Statement)]
            job[f"# TODO(migration): Groovy 'script' block not converted: {' ; '.join(raw)[:120]}"] = None
            self.manual(where, "Groovy 'script { }' block - rewrite as shell commands")
            sh_lines: list[str] = []
            for c in b.children:
                if isinstance(c, Statement) and split_call(c.text)[0] in ("sh", "echo"):
                    sh_lines.extend(self._step(c, job, where))
            return sh_lines
        self.manual(where, f"block step '{b.name}' not translated")
        return self._steps(b.children, job, where)

    def _step(self, s: Statement, job: dict, where: str) -> list[str]:
        name, rest = split_call(s.text)
        pos, named = parse_args(rest)
        first = unquote(named.get("script", pos[0] if pos else "''"))

        if name in ("sh", "bat", "powershell", "pwsh"):
            if name != "sh":
                self.manual(where, f"'{name}' step - needs a Windows runner (tags: [windows])")
            if "returnStdout" in named or "returnStatus" in named:
                self.manual(where, f"{name} with returnStdout/returnStatus - capture output in shell instead")
            return [map_env_refs(first)]
        if name == "echo":
            msg = map_env_refs(first).replace('"', '\\"')
            return [f'echo "{msg}"']
        if name == "archiveArtifacts":
            paths = unquote(named.get("artifacts", pos[0] if pos else "''"))
            art = job.setdefault("artifacts", {})
            art.setdefault("paths", []).extend(p.strip() for p in paths.split(",") if p.strip())
            art.setdefault("expire_in", "1 week")
            self.info(where, f"archiveArtifacts -> artifacts:paths {paths}")
            return []
        if name == "junit":
            path = unquote(named.get("testResults", pos[0] if pos else "''"))
            art = job.setdefault("artifacts", {})
            art["when"] = "always"
            art.setdefault("reports", {})["junit"] = path
            self.info(where, "junit -> artifacts:reports:junit (shown in merge requests)")
            return []
        if name == "stash":
            inc = unquote(named.get("includes", "'**'"))
            art = job.setdefault("artifacts", {})
            art.setdefault("paths", []).extend(p.strip() for p in inc.split(",") if p.strip())
            art.setdefault("expire_in", "1 day")
            self.info(where, "stash -> artifacts (later stages download them automatically)")
            return []
        if name == "unstash":
            self.info(where, "unstash dropped - artifacts from earlier stages are downloaded automatically")
            return []
        if name == "checkout":
            self.info(where, "checkout scm dropped - GitLab clones the repository automatically")
            return []
        if name in ("cleanWs", "deleteDir"):
            self.info(where, f"{name} dropped - runners start from a clean checkout")
            return []
        if name == "sleep":
            return [f"sleep {unquote(named.get('time', pos[0] if pos else '1'))}"]
        if name == "error":
            return [f'echo "{first}" >&2', "exit 1"]
        if name == "input":
            job["when"] = "manual"
            self.info(where, "input -> when: manual")
            return []
        if name == "build":
            self.manual(where, f"build job: {named.get('job', rest)} - use 'trigger:' (downstream pipeline)")
            return []
        if name == "git":
            self.manual(where, "git step - GitLab clones this project automatically; for other repos use 'git clone' "
                               "with CI_JOB_TOKEN")
            return []
        if name in ("publishHTML", "recordIssues", "jacoco", "cobertura"):
            self.manual(where, f"{name} - use artifacts:reports (coverage_report / codequality) or GitLab Pages")
            return []
        if name in ("mail", "emailext", "slackSend"):
            self.manual(where, f"{name} - use GitLab notifications / Slack integration instead")
            return []
        self.manual(where, f"step '{s.text[:60]}' not translated")
        return []

    # ------------------------------------------------------------------
    def _stage_post(self, post: Block, job: dict, where: str) -> None:
        after: list[str] = []
        for cond in post.blocks():
            lines = self._steps(cond.children, job, f"{where} post.{cond.name}")
            if not lines:
                continue
            if cond.name in ("always", "cleanup"):
                after.extend(lines)
            elif cond.name in ("success", "failure"):
                status = "success" if cond.name == "success" else "failed"
                after.append(f'if [ "$CI_JOB_STATUS" = "{status}" ]; then\n'
                             + "\n".join("  " + ln for ln in lines) + "\nfi")
            else:
                self.manual(where, f"post.{cond.name} has no direct equivalent")
        if after:
            job["after_script"] = after
            self.info(where, "stage post -> after_script (with $CI_JOB_STATUS checks)")

    def _pipeline_post(self, post: Block) -> None:
        mapping = {"always": "always", "cleanup": "always", "success": "on_success", "failure": "on_failure"}
        for cond in post.blocks():
            when = mapping.get(cond.name)
            where = f"pipeline post.{cond.name}"
            if not when:
                self.manual(where, "no direct equivalent (unstable/aborted/changed)")
                continue
            job: dict = {"stage": ".post"}
            script = self._steps(cond.children, job, where)
            if not script:
                continue
            job["script"] = script
            job["when"] = when
            self.jobs[f"post-{cond.name}"] = self._order(job)
            self.info(where, f"-> job in .post stage with when: {when}")


